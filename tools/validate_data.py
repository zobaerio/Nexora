#!/usr/bin/env python3
"""NEXORA — committed data validation harness (Audit Unit AD, milestone 1).

Every cross-reference that previous units verified with ad-hoc scripts is
re-checked here, from the repo, forever. Run before any simulation or data
change ships:

    python3 tools/validate_data.py

Exit code 0 = all checks pass. Any failure prints FAIL lines and exits 1.

Checks (from docs/AUDIT-AND-CHECKLIST.md §2/§7):
- All 11 JSON data files parse.
- npc-schedules profession templates match professions.json ids 1:1;
  the 3 life-stage templates exist.
- district1-blockout plots match buildings-district1 properties 1:1 by id.
- Residential stock == 140 units honouring the `part_of` rule
  (single-unit entries counted inside their parents are excluded).
- clothing.json price_refs resolve into prices.json's clothing table;
  profession uniforms cover all 11 professions.
- vehicles.json price_refs resolve into prices.json vehicles, or are
  null (the documented non-buyable gap, GDD-07 §8).
- missions.json zone_refs / profession_refs resolve.
- Wage bands: professions.json income_band_monthly must equal
  prices.json wages_monthly for all 11 professions (the audit §4.2
  duplication is guarded here until Unit AE single-sources it).
- Schedule activities stay within the 8-activity GDD-06 vocabulary and
  location tokens within the known anchor set.
- weather-presets.json carries the 9 canonical preset ids.
- city2-shibnagar.json (Session 03 Unit 01, GENERATED by
  tools/sim/citygen.py): stays labelled generated; its property /
  plot / road cross-references resolve inside the file; its
  residential stock is 39 units.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")

FAILURES = []
NOTES = []


def load(name):
    with open(os.path.join(DATA, name)) as f:
        return json.load(f)


def check(cond, label, detail=""):
    if cond:
        print(f"  ok: {label}")
    else:
        FAILURES.append(label)
        print(f"  FAIL: {label} {detail}")


def main():
    names = ["professions.json", "npc-schedules.json",
             "buildings-district1.json", "district1-blockout.json",
             "prices.json", "weather-presets.json", "missions.json",
             "clothing.json", "vehicles.json", "planets.json",
             "city2-shibnagar.json"]
    data = {}
    for n in names:
        try:
            data[n] = load(n)
        except Exception as e:  # parse failure is a failed check
            check(False, f"{n} parses", f"({e})")
    if FAILURES:
        return finish()
    print(f"  ok: all {len(names)} JSON files parse")

    professions = data["professions.json"]["professions"]
    prof_ids = [p["id"] for p in professions]
    schedules = data["npc-schedules.json"]
    sched_ids = [s["profession_id"] for s in schedules["schedules"]]
    check(sorted(prof_ids) == sorted(sched_ids) and len(prof_ids) == 11,
          "professions <-> schedules 1:1 (11 ids)",
          f"prof={sorted(prof_ids)} sched={sorted(sched_ids)}")
    check(sorted(schedules["life_stage_templates"].keys()) ==
          ["child_school_day", "elder_day", "student_day"],
          "3 life-stage templates present")

    buildings = data["buildings-district1.json"]["properties"]
    blockout = data["district1-blockout.json"]
    plots = blockout.get("plots") or blockout.get("properties") or []
    plot_ids = [p.get("building_id") or p.get("id") for p in plots]
    bldg_ids = [b["id"] for b in buildings]
    check(sorted(plot_ids) == sorted(bldg_ids),
          "blockout plots <-> buildings 1:1 by id",
          f"plots={len(plot_ids)} buildings={len(bldg_ids)}")

    res = [b for b in buildings
           if b["property_type"] in ("apartment", "house")]
    naive = sum(b.get("units", 1) for b in res)
    stock = sum(b.get("units", 1) for b in res if "part_of" not in b)
    check(stock == 140, "residential stock == 140 (part_of rule)",
          f"naive={naive} part_of-adjusted={stock}")
    NOTES.append(f"residential units: naive {naive}, part_of-adjusted {stock}")

    prices = data["prices.json"]
    clothing_prices = {i["id"] for i in prices["clothing"]["items"]}
    clothing = data["clothing.json"]
    bad = [i["id"] for i in clothing["items"]
           if i["price_ref"] not in clothing_prices]
    check(not bad, "clothing price_refs resolve (31 items)",
          f"unresolved={bad}")
    uniforms = clothing.get("profession_uniforms", [])
    uniform_ids = {u["profession_id"] for u in uniforms}
    check(uniform_ids == set(prof_ids),
          "profession uniforms cover all 11 professions",
          f"missing={set(prof_ids) - uniform_ids}")
    bad = [i for u in uniforms for i in u.get("outfit_item_ids", [])
           if i not in {c["id"] for c in clothing["items"]}]
    check(not bad, "uniform outfit_item_ids resolve to clothing items",
          f"unresolved={bad}")

    vehicle_prices = {v["id"] for v in prices["vehicles"]}
    bad = []
    nulls = []
    for v in data["vehicles.json"]["vehicles"]:
        ref = v.get("price_ref")
        if ref is None:
            nulls.append(v["id"])
        elif ref not in vehicle_prices:
            bad.append(v["id"])
    check(not bad, "vehicle price_refs resolve or are documented nulls",
          f"unresolved={bad}")
    NOTES.append(f"vehicles with null price_ref (documented gap): {nulls}")

    zones = set(data["buildings-district1.json"]["zones"])
    bad = []
    for m in data["missions.json"]["missions"]:
        for z in m.get("zone_refs", []):
            if z not in zones:
                bad.append((m["id"], z))
        for p in m.get("profession_refs", []):
            if p not in prof_ids:
                bad.append((m["id"], p))
    check(not bad, "mission zone_refs/profession_refs resolve",
          f"bad={bad}")

    wages = {w["profession_id"]: w for w in prices["wages_monthly"]}
    drift = []
    for p in professions:
        band = p["income_band_monthly"]
        w = wages.get(p["id"])
        if w is None or any(w[t] != band[t]
                            for t in ("entry", "mid", "senior")):
            drift.append(p["id"])
    check(not drift,
          "wage bands equal in professions.json and prices.json (11/11)",
          f"drift={drift}")
    NOTES.append("wage bands are stored twice (audit §4.2); this check "
                 "guards the duplication until Unit AE single-sources it")

    # -- Queue 6: Units AH + AI — priced tutoring / part-time work,
    #    medicine table + sited pharmacy --------------------------
    # Tutoring must reconcile (rate x sessions = monthly typical) and
    # stay a side-income: below the teacher's own entry wage.
    tut = prices.get("tutoring", {})
    check(tut.get("per_session_ncr", 0) > 0
          and tut.get("monthly_typical_ncr")
          == tut.get("per_session_ncr", 0)
          * tut.get("sessions_per_month_typical", 0),
          "tutoring rate positive and monthly typical reconciles",
          f"tutoring={tut}")
    teacher_entry = next(p["income_band_monthly"]["entry"]
                         for p in professions if p["id"] == "teacher")
    check(tut.get("monthly_typical_ncr", 0) < teacher_entry,
          "tutoring typical monthly stays a side-income (< teacher entry)",
          f"monthly={tut.get('monthly_typical_ncr')} teacher_entry={teacher_entry}")
    # Part-time work must reconcile (rate x blocks/week x 4 = monthly)
    # and stay below the lowest full profession entry band.
    pt = prices.get("part_time_student_work", {})
    lowest_entry = min(p["income_band_monthly"]["entry"]
                       for p in professions)
    check(pt.get("monthly_typical_ncr")
          == pt.get("per_block_ncr", 0)
          * pt.get("blocks_per_week_typical", 0) * 4
          and pt.get("monthly_typical_ncr", 0) < lowest_entry,
          "part-time monthly reconciles and stays below lowest entry band",
          f"monthly={pt.get('monthly_typical_ncr')} lowest_entry={lowest_entry}")
    # Medicine: unique ids, positive prices, band-tied uses; the
    # pharmacy must sit in an existing commercial (shop) property and
    # be recorded as one of its tenants; the medical budget line must
    # be positive and ordered by band.
    med = prices.get("medicine", {})
    med_items = med.get("items", [])
    check(len({m["id"] for m in med_items}) == len(med_items)
          and all(m["price_ncr"] > 0 for m in med_items),
          "medicine ids unique and prices positive",
          f"ids={[m['id'] for m in med_items]}")
    check(all(set(m.get("used_for_bands", [])) <= {"unwell", "injured",
                                                  "serious"}
              for m in med_items),
          "medicine uses reference GDD-12 care bands",
          f"bad={[m['id'] for m in med_items if set(m.get('used_for_bands', [])) - {'unwell', 'injured', 'serious'}]}")
    pharm = next((b for b in buildings
                  if b["id"] == med.get("pharmacy_property_id")), None)
    check(pharm is not None and pharm.get("property_type") == "shop",
          "pharmacy sits in an existing commercial (shop) property",
          f"pharmacy_property_id={med.get('pharmacy_property_id')}")
    check(pharm is not None
          and any(t.get("trade") == "pharmacy"
                  for t in pharm.get("tenants", [])),
          "pharmacy is recorded as a tenant of its sited property",
          f"tenants={pharm.get('tenants') if pharm else None}")
    med_monthly = prices.get("living_costs_monthly", {}).get(
        "medical_monthly", {})
    check(all(med_monthly.get(b, 0) > 0 for b in
              ("lower", "mid", "upper"))
          and med_monthly.get("lower", 0)
          <= med_monthly.get("mid", 0)
          <= med_monthly.get("upper", 0),
          "medical monthly budget positive and ordered by band",
          f"medical_monthly={med_monthly}")

    acts, locs = set(), set()
    for s in schedules["schedules"]:
        for b in s["template"]:
            acts.add(b["activity"])
            locs.add(b["location"])
    for t in schedules["life_stage_templates"].values():
        for b in t:
            acts.add(b["activity"])
            locs.add(b["location"])
    check(acts <= {"sleep", "home", "commute", "work", "break", "errand",
                   "leisure", "study"},
          "schedule activities within GDD-06 vocabulary",
          f"extra={acts - {'sleep','home','commute','work','break','errand','leisure','study'}}")
    check(locs <= {"home", "workplace", "transit", "tea_stall", "market",
                   "riverfront", "park", "restaurant", "college_para",
                   "college", "school", "mobile"},
          "schedule locations within known anchor tokens",
          f"extra={locs - {'home','workplace','transit','tea_stall','market','riverfront','park','restaurant','college_para','college','school','mobile'}}")

    preset_ids = sorted(p["id"] for p in
                        data["weather-presets.json"]["presets"])
    check(preset_ids == ["clear_day", "cloudy", "fog", "night_clear",
                         "rain", "snow", "storm", "sunrise_clear",
                         "windy"],
          "9 canonical weather preset ids", f"got={preset_ids}")

    # Session 03 Unit 01: the generated second city. The honesty
    # rule is guarded here: generated data must stay labelled.
    c2 = data["city2-shibnagar.json"]
    check(c2.get("generated") is True
          and "GENERATED" in c2.get("warning", "")
          and "citygen" in c2.get("generated_by", ""),
          "city2 stays labelled as generated data")
    check(c2["city"]["kind"] == "generated_town"
          and c2["city"]["city_id"] == "shibnagar_town",
          "city2 identity is the generated town")
    c2_zones = set(c2["zones"])
    check(set(c2["zone_boxes_m"]) == c2_zones,
          "city2 zone boxes cover exactly its zones")
    check(all(p["zone_id"] in c2_zones for p in c2["properties"]),
          "city2 property zone refs resolve")
    c2_buildings = {p["id"] for p in c2["properties"]}
    check(all(pl["building_id"] is None
              or pl["building_id"] in c2_buildings
              for pl in c2["plots"]),
          "city2 plot building refs resolve (null = vacant)")
    check(all(pl["zone_id"] in c2_zones for pl in c2["plots"]),
          "city2 plot zone refs resolve")
    check(all(r["class"] in {"arterial", "collector", "local",
                             "lane", "promenade"}
              for r in c2["road_segments"]),
          "city2 road classes within the GDD-07 vocabulary")
    c2_stock = sum(p.get("units", 1) for p in c2["properties"]
                   if p["property_type"] in ("apartment", "house"))
    check(c2_stock == 39, "city2 residential stock == 39 units",
          f"got={c2_stock}")
    NOTES.append("city2-shibnagar.json is GENERATED (citygen.py); "
                 "its label is a guarded honesty rule, not a defect")

    # Session 04: the economy layer's data files. Goods carry an
    # anchor into prices.json or an explicit SIM MODEL label;
    # recipes reference real goods and real categories; the
    # economy config's tax rules reference (never copy) the
    # canonical prices.json rates.
    for n in ("economy-goods.json", "production-recipes.json",
              "economy-config.json"):
        try:
            data[n] = load(n)
            print(f"  ok: {n} parses")
        except Exception as e:
            check(False, f"{n} parses", f"({e})")
    if "economy-goods.json" in data:
        goods = data["economy-goods.json"]["goods"]
        good_ids = [g["id"] for g in goods]
        check(len(good_ids) == len(set(good_ids)),
              "economy goods have unique ids")
        check(all(g["base_price_ncr"] > 0 for g in goods),
              "economy goods have positive base prices")
        unlabelled = [g["id"] for g in goods
                      if not g.get("anchor")
                      and "SIM MODEL" not in g.get("sim_model_note", "")]
        check(not unlabelled,
              "every unanchored good price is labelled SIM MODEL",
              f"unlabelled={unlabelled}")
        cats = {g["category"] for g in goods}
        check(cats <= {"food", "clothing", "household", "agriculture",
                       "manufactured"},
              "goods categories within the Session 04 vocabulary",
              f"extra={cats}")
    if "production-recipes.json" in data \
            and "economy-goods.json" in data:
        good_ids = {g["id"] for g in data["economy-goods.json"]["goods"]}
        recipes = data["production-recipes.json"]["recipes"]
        bad = []
        for r in recipes:
            if r["output_good"] not in good_ids:
                bad.append((r["id"], "output"))
            for g in r["goods_in"]:
                if g not in good_ids:
                    bad.append((r["id"], g))
        check(not bad, "recipe goods_in/output resolve to goods",
              f"bad={bad}")
        check(all(r["units_per_run"] > 0 and r["crew_per_run"] > 0
                  for r in recipes),
              "recipes have positive run size and crew")
    if "economy-config.json" in data:
        cfg = data["economy-config.json"]
        check(cfg["currency"]["code"] == "NCr"
              and cfg["currency"]["name"] in prices["currency"],
              "economy config currency matches prices.json")
        check(cfg["tax_rules"]["income_tax"]["source"].startswith(
            "prices.json"), "income tax rule references prices.json")
        check(0 < cfg["tax_rules"]["sales_tax_percent"] < 100
              and 0 < cfg["tax_rules"]["import_tariff_percent"] < 100,
              "SIM MODEL tax rates are sane percents")
        check(cfg["bank"]["genesis_capital_ncr"] > 0,
              "bank genesis capital is positive")

    # Session 05: the government layer's configuration. Party
    # ideology is data with the five canonical dimensions;
    # election seats reference the two real cities; budget
    # shares cannot exceed the forecast; legal bounds are
    # ordered; the diplomacy partner is the labelled model
    # account, never a second country.
    try:
        data["government-config.json"] = load("government-config.json")
        print("  ok: government-config.json parses")
    except Exception as e:
        check(False, "government-config.json parses", f"({e})")
    if "government-config.json" in data:
        g = data["government-config.json"]
        check(g["country"]["currency_code"] == "NCr",
              "government country currency is NCr")
        genesis = g["parties"]["genesis"]
        pids = [p["party_id"] for p in genesis]
        check(len(pids) == len(set(pids)),
              "genesis party ids are unique")
        dims = {"economy", "welfare", "services", "development",
                "law_order"}
        check(all(set(p["stances"]) == dims
                  and all(0 <= v <= 100
                          for v in p["stances"].values())
                  for p in genesis),
              "party stances are 0-100 over the 5 dimensions")
        seats = g["elections"]["seats_per_city"]
        check(set(seats) == {"rupsha_city", "shibnagar_town"}
              and all(v > 0 for v in seats.values()),
              "election seats cover exactly the two real cities")
        check(g["country"]["capital_city_id"] in seats,
              "the capital is a constituency")
        check(g["elections"]["eligibility_age"] >= 18
              and g["elections"]["term_months"] > 0,
              "election rules are sane (18+, positive term)")
        shares = g["budget"]["allocation_shares"]
        check(all(v >= 0 for v in shares.values())
              and sum(shares.values()) <= 1.0,
              "budget allocation shares sum to <= 1",
              f"sum={sum(shares.values())}")
        bounds_ok = all(
            isinstance(b, list) and len(b) == 2 and 0 <= b[0] < b[1]
            for k, b in g["laws"].items() if k.endswith("_bounds"))
        check(bounds_ok, "legal bounds are ordered pairs")
        check(len(g["laws"]["constitution"]) >= 1,
              "the constitution is present as data")
        pol = g["policies"]
        check(all(pol[k]["duration_months"] > 0 for k in pol
                  if isinstance(pol[k], dict)
                  and "duration_months" in pol[k]),
              "policy durations are positive")
        check(all(v > 0 for v in
                  g["offices"]["allowance_ncr_per_month"].values()),
              "office allowances are positive")
        check(g["diplomacy"]["partner"]["account_id"]
              == "SYS-EXTERNAL"
              and g["diplomacy"]["genesis_grant_ncr"] > 0
              and abs(g["diplomacy"]
                      ["trade_agreement_tariff_delta_percent"])
              <= g["laws"]["import_tariff_percent_bounds"][1],
              "diplomacy partner is the labelled model account")

    # -- Session 06: education-health-config.json ------------------
    # Institution + facility building ids must resolve to real
    # buildings in one of the two city files (no fabricated
    # institutions); curriculum skills must be canonical skill
    # ids; medication ids unique with positive stock/cost; grade
    # bands strictly descending; disease parameters in range;
    # recovery windows ordered (treated shorter than untreated).
    try:
        data["education-health-config.json"] = load(
            "education-health-config.json")
        print("  ok: education-health-config.json parses")
    except Exception as e:
        check(False, "education-health-config.json parses", f"({e})")
    if "education-health-config.json" in data:
        eh = data["education-health-config.json"]
        all_buildings = {b["id"] for b in buildings}
        all_buildings |= {p["id"] for p in
                          data["city2-shibnagar.json"]["properties"]}
        inst = eh["education"]["institutions"]
        check(all(i["building_id"] in all_buildings for i in inst),
              "education institutions sit in real buildings",
              f"ids={[i['building_id'] for i in inst]}")
        check(len({i["institution_id"] for i in inst}) == len(inst),
              "institution ids are unique")
        types = eh["education"]["institution_types"]
        check(all(i["type"] in types for i in inst)
              and all(t["capacity_students"] > 0
                      and t["monthly_budget_ncr"] > 0
                      for t in types.values()),
              "institution types have positive capacity + budget")
        facs = eh["health"]["facilities"]
        check(all(f["building_id"] in all_buildings for f in facs),
              "healthcare facilities sit in real buildings")
        check(len({f["facility_id"] for f in facs}) == len(facs),
              "facility ids are unique")
        prof_skills = set()
        for p in professions:
            prof_skills.update(p["primary_skills"])
        # GDD-11's own vocabulary beyond primary_skills: the
        # school foundation skill and the classroom discipline
        # skill GDD-11 §3 names explicitly.
        prof_skills.update({"subject_knowledge", "discipline"})
        cur = eh["education"]["curricula"]
        subjects = list(cur["school"]["subjects"])
        for prog in cur["programmes"].values():
            subjects.extend(prog)
        bad_skills = [s["id"] for s in subjects
                      if s["skill"] not in prof_skills]
        check(not bad_skills,
              "curriculum skills are canonical skill ids",
              f"bad={bad_skills}")
        check(all(s["prerequisites"] is not None
                  and all(pre in {x['id'] for x in subjects}
                          or pre in {x['id'] for x in
                                     cur['school']['subjects']}
                          for pre in s["prerequisites"])
                  for s in subjects),
              "curriculum prerequisites resolve to subjects")
        bands = eh["education"]["examinations"]["grade_bands"]
        mins = [b["min_score"] for b in bands]
        check(mins == sorted(mins, reverse=True)
              and len(set(mins)) == len(mins) and mins[-1] == 0,
              "grade bands are strictly descending to 0")
        w = eh["education"]["examinations"]["weights"]
        check(abs(sum(w.values()) - 1.0) < 1e-9,
              "examination weights sum to 1", f"sum={sum(w.values())}")
        meds = eh["health"]["medications"]["items"]
        check(len({m["id"] for m in meds}) == len(meds)
              and all(m["target_stock"] > 0
                      and m["procurement_ncr_per_unit"] > 0
                      for m in meds),
              "medication ids unique; stock + unit cost positive")
        known_bands = {"unwell", "injured", "serious", "vaccination",
                       "chronic", "birth_care"}
        check(all(set(m["used_for_bands"]) <= known_bands
                  for m in meds),
              "medication uses reference known care bands")
        rec = eh["health"]["recovery_days"]
        check(all(rec[b]["treated"][1] <= rec[b]["untreated"][1]
                  and rec[b]["treated"][0] >= 1
                  for b in ("unwell", "injured", "serious")),
              "treated recovery windows never exceed untreated")
        dis = eh["disease"]["diseases"]
        check(all(0 < d["transmission_per_contact_day"] <= 1
                  and 0 <= d["vaccine_effectiveness"] <= 1
                  and d["recovery_days"][0] >= 1
                  and d["immunity_days"] > 0 for d in dis),
              "disease parameters are in range")
        check(isinstance(eh["disease"]["scenarios"], list),
              "disease scenarios are a list (empty by default)")

    # -- Session 07: transport-config.json -------------------------
    # Transit stops must be real zone ids of the route's city (the
    # ferry's second stop is the other city's ghat zone); vehicle
    # types must resolve into vehicles.json; tank capacities and
    # emission factors must cover every fuel type vehicles.json
    # uses; the ferry route id must be Session 03's persisted
    # regional connection.
    try:
        data["transport-config.json"] = load("transport-config.json")
        print("  ok: transport-config.json parses")
    except Exception as e:
        check(False, "transport-config.json parses", f"({e})")
    if "transport-config.json" in data:
        tc = data["transport-config.json"]
        vehicles = {v["id"]: v for v in load("vehicles.json")["vehicles"]}
        zones_by_city = {
            "rupsha_city": set(data["buildings-district1.json"]
                               ["zones"]),
            "shibnagar_town": set(data["city2-shibnagar.json"]["zones"]),
        }
        all_zones = set().union(*zones_by_city.values())
        routes = tc["transit_routes"]
        check(len({r["route_id"] for r in routes}) == len(routes),
              "transit route ids are unique")
        check(all(r["vehicle_type"] is None
                  or r["vehicle_type"] in vehicles for r in routes),
              "transit vehicle types resolve into vehicles.json")
        check(all(all(s in zones_by_city[r["city_id"]]
                      or (r["kind"] == "ferry" and s in all_zones)
                      for s in r["stops"]) for r in routes),
              "transit stops are real zone ids")
        check(all(r["terminal_building_id"] in
                  {b["id"] for b in buildings}
                  or r["terminal_building_id"] in
                  {p["id"] for p in data["city2-shibnagar.json"]
                   ["properties"]} for r in routes),
              "transit terminals are real buildings")
        check(any(r["route_id"] == "RC-FERRY-1" and r["kind"] == "ferry"
                  for r in routes),
              "ferry route is Session 03's RC-FERRY-1 connection")
        fuel_types = {v["fuel_type"] for v in vehicles.values()}
